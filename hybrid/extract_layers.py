"""Step 1: segment a generated collage plate into bird / sea / mountain masks.

Prototype: thresholds, the bird outline and the sea-line rule are hand-tuned for
src/jingwei_cover.jpg (generated by Gemini in Paperwing Studio). Writes masks.npy and masks_overlay.jpg.
"""
import cv2, numpy as np
import os
os.chdir(os.path.dirname(os.path.abspath(__file__)))  # paths below are relative to hybrid/
im = cv2.imread("src/jingwei_cover.jpg")
H, W = im.shape[:2]
lab = cv2.cvtColor(im, cv2.COLOR_BGR2LAB).astype(np.float32)
paper = np.median(np.concatenate([lab[:6].reshape(-1, 3), lab[60:300, -6:].reshape(-1, 3)]), 0)
dist = np.linalg.norm(lab - paper, axis=2)
ink = dist > 9
hsv = cv2.cvtColor(im, cv2.COLOR_BGR2HSV)
hue, sat = hsv[..., 0].astype(int), hsv[..., 1].astype(int)

bird_poly = np.array([(462,88),(560,105),(655,160),(705,215),(760,188),(805,168),(852,180),(880,212),(922,132),(952,116),
    (1002,168),(1003,214),(962,232),(968,282),(955,348),(878,350),(864,336),(824,366),(806,352),(804,410),(793,520),(768,645),
    (718,648),(688,565),(648,485),(628,425),(572,452),(520,474),(418,472),(398,410),(420,352),(482,330),(560,318),(598,304),
    (545,308),(503,256),(476,196),(456,128)], np.int32)
inpoly = np.zeros((H, W), np.uint8); cv2.fillPoly(inpoly, [bird_poly], 1); inpoly = inpoly.astype(bool)

# sea line: top of blue ink outside the bird outline, interpolated under the bird
blueish = (hue > 95) & (hue < 130) & ink
top = np.full(W, -1.0)
for x in range(W):
    ys = np.where(blueish[300:, x] & ~inpoly[300:, x])[0]
    if len(ys) and not inpoly[300:480, x].any():
        top[x] = 300 + ys[0]
good = top >= 0
top = np.interp(np.arange(W), np.where(good)[0], top[good])
top = cv2.GaussianBlur(top.reshape(1, -1).astype(np.float32), (0, 0), 2).ravel()
yy = np.arange(H)[:, None]
below = yy >= top[None, :] - 1

# bird above the sea line = anything that isn't paper inside the outline
bird = (ink & inpoly & ~below).astype(np.uint8)
# bird below the sea line: GrabCut seeded by feather colours vs sea blues
gc = np.full((H, W), cv2.GC_BGD, np.uint8)
zone = inpoly & below
gc[zone] = cv2.GC_PR_FGD
feather = ((hue >= 78) & (hue <= 94) | (hue <= 12) | (hue >= 165) | ((hue >= 13) & (hue <= 32))) & (sat > 70)
gc[zone & feather] = cv2.GC_FGD
gc[zone & (hue > 100) & (hue < 128) & (sat > 60)] = cv2.GC_PR_BGD
gc[bird > 0] = cv2.GC_FGD
x0, x1, y0, y1 = 380, 1010, 280, 668
sub = gc[y0:y1, x0:x1].copy()
bgd, fgd = np.zeros((1, 65)), np.zeros((1, 65))
cv2.grabCut(im[y0:y1, x0:x1], sub, None, bgd, fgd, 8, cv2.GC_INIT_WITH_MASK)
gc[y0:y1, x0:x1] = sub
bird = np.isin(gc, [cv2.GC_FGD, cv2.GC_PR_FGD]).astype(np.uint8)
bird = cv2.morphologyEx(bird, cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
n, lbl, st, _ = cv2.connectedComponentsWithStats(bird, 8)
bird = np.isin(lbl, [i for i in range(1, n) if st[i, cv2.CC_STAT_AREA] > 300]).astype(np.uint8)
# fill holes enclosed by the bird (pale head feathers)
ff = bird.copy() * 255; m = np.zeros((H + 2, W + 2), np.uint8); cv2.floodFill(ff, m, (0, 0), 128)
bird[ff == 0] = 1

sea = below.astype(np.uint8)
mountain = (((hue < 25) & (sat > 70) & ink) & (yy > 380) & (np.arange(W)[None, :] > 800) & ~below & (bird == 0)).astype(np.uint8)
mountain = cv2.morphologyEx(mountain, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
np.save("masks.npy", {"bird": bird, "sea": sea, "mountain": mountain, "paper": paper, "top": top}, allow_pickle=True)
over = im.copy()
for msk, col in ((sea & (1 - bird), (255, 0, 0)), (mountain, (0, 160, 0)), (bird, (0, 0, 255))):
    sel = msk > 0
    over[sel] = (0.45 * over[sel] + 0.55 * np.array(col)).astype(np.uint8)
cv2.imwrite("masks_overlay.jpg", over)
print("bird", bird.sum(), "sea", sea.sum(), "mountain", mountain.sum())
